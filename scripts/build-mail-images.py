"""Bundle only curated public email images into the server transport; never private data."""
import base64, hashlib, json, re, sys
from pathlib import Path
root=Path(__file__).resolve().parents[1]
manifest=json.loads((root/'hub/cloud/email-assets.js').read_text().split('=',1)[1].strip().rstrip(';'))
files=sorted(set(re.findall(r'[a-z-]+-v\d+\.(?:png|jpg)',(root/'hub/email-template.js').read_text())))
images={}
for name in files:
    data=(root/'images/email'/name).read_bytes()
    assert len(data)==manifest[name]['size'] and hashlib.sha256(data).hexdigest()==manifest[name]['sha256'], f'Email image integrity mismatch: {name}'
    images[name]=base64.b64encode(data).decode('ascii')
content='// Generated by scripts/build-mail-images.py. Public curated images. SERVER ONLY.\nexport const emailImageData = Object.freeze('+json.dumps(images,separators=(',',':'))+');\n'
output=root/'hub/cloud/email-image-data.js'
if '--check' in sys.argv:
    assert output.exists() and output.read_text()==content, 'Run python3 scripts/build-mail-images.py and include the generated server module.'
else:
    output.write_text(content)
print(f'Verified {len(images)} bundled email images; no runtime image fetch required.')
